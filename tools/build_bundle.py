#!/usr/bin/env python3
"""Regenerate data/bundle.js from data/*.json (so index.html works from file:// and offline).
Run after editing any data/*.json or after a converter (update_from_*.py, build_meta_comps.py)."""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'data')
REQUIRED = ['patch-info', 'champions', 'traits', 'items', 'augments', 'shop-odds', 'game-rules']
OPTIONAL = ['meta-comps', 'encounters']
out = {}
for f in REQUIRED + OPTIONAL:
    p = os.path.join(DATA, f + '.json')
    if os.path.exists(p):
        out[f] = json.load(open(p, encoding='utf8'))
    elif f in REQUIRED:
        raise SystemExit(f'missing required data/{f}.json')
with open(os.path.join(DATA, 'bundle.js'), 'w', encoding='utf8') as fh:
    fh.write('/* AUTO-GENERATED by tools/build_bundle.py — edit data/*.json then rerun, or import JSON in the app. */\n')
    fh.write('window.TFT_DATA_BUNDLE=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('bundle.js:', ', '.join(f'{k}' for k in out), f'({os.path.getsize(os.path.join(DATA, "bundle.js")) // 1024} KB)')

# ---- asset index (portraits / trait icons / item icons) for the app and the service worker ----
A = os.path.join(ROOT, 'assets')
idx = {k: sorted(os.path.splitext(f)[0] for f in os.listdir(os.path.join(A, k))) for k in ('champions', 'traits', 'items') if os.path.isdir(os.path.join(A, k))}
ext = {'champions': 'webp', 'traits': 'svg', 'items': 'webp'}
files = [f'assets/{k}/{i}.{ext[k]}' for k, ids in idx.items() for i in ids]
with open(os.path.join(A, 'index.js'), 'w', encoding='utf8') as fh:
    fh.write('/* AUTO-GENERATED by tools/build_bundle.py */\nwindow.TFT_ASSETS=' + json.dumps({'ext': ext, **idx}, separators=(',', ':')) + ';\n')
json.dump(files, open(os.path.join(A, 'files.json'), 'w'))
print('assets:', {k: len(v) for k, v in idx.items()}, len(files), 'files')
